/**
 * Deterministic G2–G6 車内アナウンス copy from word surfaces + elementary readings.
 * One row per 配当 kanji. Never reuses another station's quoted kanji.
 * Editorial G1 (and a few extra) rows are left untouched.
 */
import { writeFileSync } from "node:fs";
import { ANNOUNCEMENTS_G1 } from "../src/data/announcements.ts";
import { KYOIKU } from "../src/data/kyoiku.ts";
import { exampleWordSurfaces } from "../src/lib/echo-surfaces.ts";
import { primaryElementaryReading } from "../src/lib/readings.ts";

function kataToHira(s) {
  return [...String(s ?? "")]
    .map((ch) => {
      const c = ch.charCodeAt(0);
      if (c >= 0x30a1 && c <= 0x30f6) return String.fromCharCode(c - 0x60);
      return ch;
    })
    .join("");
}

function genericId(kanji) {
  return `g-${(kanji.codePointAt(0) ?? 0).toString(16)}`;
}

function isVerbOrAdj(word) {
  if (word.length >= 2 && /[ぁ-ゖ]$/.test(word) && /[一-龯]/.test(word)) {
    if (/い$/.test(word)) return true;
    if (/[うくぐすつぬむる]$/.test(word)) return true;
  }
  return false;
}

function pickCompound(char) {
  const words = exampleWordSurfaces(char).filter((s) => s.text.includes(char) && s.text !== char);
  words.sort((a, b) => a.text.length - b.text.length || a.text.localeCompare(b.text, "ja"));
  return words[0] ?? null;
}

function buildRow(char) {
  const id = genericId(char);
  const compound = pickCompound(char);
  if (compound) {
    const reading = kataToHira(compound.kana || compound.reading);
    const particle = isVerbOrAdj(compound.text) ? "" : "の";
    return {
      id,
      kanji: char,
      text: `次は、${compound.text}${particle}「${char}」です。`,
      reading,
    };
  }
  const reading = kataToHira(primaryElementaryReading(char) || "");
  if (reading) {
    return {
      id,
      kanji: char,
      text: `次は、${reading}の「${char}」です。`,
      reading,
    };
  }
  return {
    id,
    kanji: char,
    text: `次は、「${char}」です。`,
    reading,
  };
}

const editorial = new Set(ANNOUNCEMENTS_G1.map((a) => a.kanji));
const rows = [];
for (const k of KYOIKU) {
  if (k.grade < 2 || k.grade > 6) continue;
  if (editorial.has(k.char)) continue;
  rows.push(buildRow(k.char));
}

const body =
  "/** Auto-generated by scripts/build-announce-g2g6.mjs. Do not edit by hand. */\n" +
  'import type { Announcement } from "./announcements.ts";\n\n' +
  "export const ANNOUNCEMENTS_G2G6: Announcement[] = [\n" +
  rows
    .map(
      (a) =>
        `  { id: ${JSON.stringify(a.id)}, kanji: ${JSON.stringify(a.kanji)}, text: ${JSON.stringify(a.text)}, reading: ${JSON.stringify(a.reading)} },`,
    )
    .join("\n") +
  "\n];\n";

const dest = new URL("../src/data/announcements-g2g6.ts", import.meta.url);
writeFileSync(dest, body);

const byGrade = {};
for (const k of KYOIKU) {
  if (k.grade < 2 || k.grade > 6) continue;
  byGrade[k.grade] ??= { total: 0, editorial: 0, built: 0 };
  byGrade[k.grade].total++;
  if (editorial.has(k.char)) byGrade[k.grade].editorial++;
  else byGrade[k.grade].built++;
}

console.log(
  JSON.stringify(
    {
      rows: rows.length,
      byGrade,
      samples: ["雲", "漢", "引", "湖"].map((c) => rows.find((r) => r.kanji === c)),
    },
    null,
    2,
  ),
);

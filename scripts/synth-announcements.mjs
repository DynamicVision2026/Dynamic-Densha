/**
 * Build-time 車内アナウンス audio.
 * One MP3 per station line: fixed chime + xAI TTS of the *exact* display text.
 * Re-run only when copy/ids change. Existing files are skipped.
 */
import { mkdirSync, existsSync, writeFileSync, readFileSync, readdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { ANNOUNCEMENTS_G1 } from "../src/data/announcements.ts";
import { ANNOUNCEMENTS_G2G6 } from "../src/data/announcements-g2g6.ts";

const OUT_DIR = new URL("../public/announce/", import.meta.url);
const TMP = "/tmp/densha-announce";
const FFMPEG = "ffmpeg";
const VOICE = "eve";
const LANGUAGE = "ja";
const CONCURRENCY = 6;

mkdirSync(new URL(OUT_DIR), { recursive: true });
mkdirSync(TMP, { recursive: true });

function ffmpeg(args) {
  const r = spawnSync(FFMPEG, ["-hide_banner", "-loglevel", "error", "-y", ...args], {
    encoding: "utf8",
  });
  if (r.status !== 0) {
    throw new Error(`ffmpeg failed: ${r.stderr || r.stdout || r.status}`);
  }
}

const chimePath = `${TMP}/chime.wav`;
ffmpeg([
  "-f",
  "lavfi",
  "-i",
  "sine=frequency=880:sample_rate=44100:duration=0.2",
  "-f",
  "lavfi",
  "-i",
  "sine=frequency=659.25:sample_rate=44100:duration=0.32",
  "-filter_complex",
  [
    "[0]afade=t=in:d=0.015,afade=t=out:st=0.15:d=0.05,volume=0.18[a]",
    "[1]adelay=240|240,afade=t=in:d=0.02,afade=t=out:st=0.26:d=0.06,volume=0.16[b]",
    "[a][b]amix=inputs=2:duration=longest,apad=pad_dur=0.2[out]",
  ].join(";"),
  "-map",
  "[out]",
  "-ar",
  "44100",
  chimePath,
]);

function writeBaked() {
  const BAKED = new URL("../src/data/announce-baked.ts", import.meta.url);
  const ids = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".mp3") && !f.startsWith("_"))
    .map((f) => f.replace(/\.mp3$/, ""))
    .sort();
  writeFileSync(
    BAKED,
    "/** Auto-generated by scripts/synth-announcements.mjs. Do not edit by hand. */\n" +
      "export const BAKED_ANNOUNCE_IDS = [\n" +
      ids.map((id) => `  ${JSON.stringify(id)},`).join("\n") +
      "\n] as const;\n",
  );
  return ids.length;
}

const apiKey = process.env.XAI_API_KEY;
if (!apiKey) {
  console.error("XAI_API_KEY missing — cannot synth speech. Existing clips kept.");
  console.log(JSON.stringify({ baked: writeBaked() }));
  process.exit(0);
}

async function tts(text, dest) {
  const res = await fetch("https://api.x.ai/v1/tts", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ text, voice_id: VOICE, language: LANGUAGE }),
  });
  if (!res.ok) {
    const err = await res.text();
    throw new Error(`TTS ${res.status}: ${err.slice(0, 200)}`);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 1000 || buf.subarray(0, 1).toString() === "{") {
    throw new Error("TTS did not return audio");
  }
  writeFileSync(dest, buf);
}

function concatChime(speechPath, outPath) {
  ffmpeg([
    "-i",
    chimePath,
    "-i",
    speechPath,
    "-filter_complex",
    [
      "[0:a]aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=mono[c]",
      "[1:a]aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=mono,volume=0.95[s]",
      "[c][s]concat=n=2:v=0:a=1[out]",
    ].join(";"),
    "-map",
    "[out]",
    "-codec:a",
    "libmp3lame",
    "-q:a",
    "4",
    outPath,
  ]);
}

const ALL = [...ANNOUNCEMENTS_G1, ...ANNOUNCEMENTS_G2G6];
const pending = ALL.filter((a) => {
  const out = new URL(`${a.id}.mp3`, OUT_DIR);
  return !(existsSync(out.pathname) && readFileSync(out.pathname).length > 8000);
});

const made = [];
const failed = [];
let cursor = 0;

async function worker() {
  while (true) {
    const idx = cursor++;
    if (idx >= pending.length) return;
    const a = pending[idx];
    const out = new URL(`${a.id}.mp3`, OUT_DIR);
    const speechPath = `${TMP}/speech-${a.id}.mp3`;
    process.stdout.write(`synth ${idx + 1}/${pending.length} ${a.id} ← ${a.text}\n`);
    try {
      await tts(a.text, speechPath);
      concatChime(speechPath, out.pathname);
      made.push(a.id);
    } catch (err) {
      try {
        await new Promise((r) => setTimeout(r, 800));
        await tts(a.text, speechPath);
        concatChime(speechPath, out.pathname);
        made.push(a.id);
      } catch (err2) {
        failed.push({ id: a.id, kanji: a.kanji, error: String(err2).slice(0, 160) });
        process.stderr.write(`fail ${a.id}: ${err2}\n`);
      }
    }
  }
}

await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));

const baked = writeBaked();
console.log(
  JSON.stringify({
    voice: VOICE,
    language: LANGUAGE,
    pending: pending.length,
    made: made.length,
    failed: failed.length,
    baked,
    failedIds: failed.slice(0, 20),
  }),
);
if (failed.length) process.exitCode = 1;

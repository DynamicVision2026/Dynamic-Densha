/**
 * Bake generic 車内アナウンス so non-curated stations are not silent.
 * - _chime / _tsugiwa / _desu glue clips (any station)
 * - G1 full-sentence MP3s (chime + "次は、「X」です。")
 * Existing files skipped. Never called on the child path.
 */
import { mkdirSync, existsSync, writeFileSync, readFileSync, readdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { ANNOUNCEMENTS_G1 } from "../src/data/announcements.ts";
import { KYOIKU } from "../src/data/kyoiku.ts";

const OUT_DIR = new URL("../public/announce/", import.meta.url);
const BAKED = new URL("../src/data/announce-baked.ts", import.meta.url);
const TMP = "/tmp/densha-announce-generic";
const FFMPEG = "ffmpeg";
const VOICE = "eve";
const LANGUAGE = "ja";

mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(TMP, { recursive: true });

function ffmpeg(args) {
  const r = spawnSync(FFMPEG, ["-hide_banner", "-loglevel", "error", "-y", ...args], {
    encoding: "utf8",
  });
  if (r.status !== 0) {
    throw new Error(`ffmpeg failed: ${r.stderr || r.stdout || r.status}`);
  }
}

function genericId(kanji) {
  return `g-${(kanji.codePointAt(0) ?? 0).toString(16)}`;
}

const chimeWav = `${TMP}/chime.wav`;
ffmpeg([
  "-f",
  "lavfi",
  "-i",
  "sine=frequency=880:sample_rate=44100:duration=0.2",
  "-f",
  "lavfi",
  "-i",
  "sine=frequency=659.25:sample_rate=44100:duration=0.32",
  "-filter_complex",
  [
    "[0]afade=t=in:d=0.015,afade=t=out:st=0.15:d=0.05,volume=0.18[a]",
    "[1]adelay=240|240,afade=t=in:d=0.02,afade=t=out:st=0.26:d=0.06,volume=0.16[b]",
    "[a][b]amix=inputs=2:duration=longest,apad=pad_dur=0.2[out]",
  ].join(";"),
  "-map",
  "[out]",
  "-ar",
  "44100",
  chimeWav,
]);

const chimeMp3 = new URL("_chime.mp3", OUT_DIR);
ffmpeg(["-i", chimeWav, "-codec:a", "libmp3lame", "-q:a", "4", chimeMp3.pathname]);

function writeBaked() {
  const ids = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".mp3") && !f.startsWith("_"))
    .map((f) => f.replace(/\.mp3$/, ""))
    .sort();
  const body =
    "/** Auto-generated by scripts/synth-announce-generic.mjs. Do not edit by hand. */\n" +
    "export const BAKED_ANNOUNCE_IDS = [\n" +
    ids.map((id) => `  ${JSON.stringify(id)},`).join("\n") +
    "\n] as const;\n";
  writeFileSync(BAKED, body);
  return ids.length;
}

const apiKey = process.env.XAI_API_KEY;
if (!apiKey) {
  console.error("XAI_API_KEY missing — glue/generic speech not synth'd. Existing clips kept.");
  console.log(JSON.stringify({ baked: writeBaked() }));
  process.exit(0);
}

async function tts(text, dest) {
  const res = await fetch("https://api.x.ai/v1/tts", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ text, voice_id: VOICE, language: LANGUAGE }),
  });
  if (!res.ok) {
    const err = await res.text();
    throw new Error(`TTS ${res.status}: ${err.slice(0, 200)}`);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 400 || buf.subarray(0, 1).toString() === "{") {
    throw new Error("TTS did not return audio");
  }
  writeFileSync(dest, buf);
}

function concatChime(speechPath, outPath) {
  ffmpeg([
    "-i",
    chimeWav,
    "-i",
    speechPath,
    "-filter_complex",
    [
      "[0:a]aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=mono[c]",
      "[1:a]aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=mono,volume=0.95[s]",
      "[c][s]concat=n=2:v=0:a=1[out]",
    ].join(";"),
    "-map",
    "[out]",
    "-codec:a",
    "libmp3lame",
    "-q:a",
    "4",
    outPath,
  ]);
}

function skipExisting(pathname) {
  return existsSync(pathname) && readFileSync(pathname).length > 4000;
}

const made = [];
const skipped = [];

async function ensureSpeechMp3(id, text, withChime) {
  const out = new URL(`${id}.mp3`, OUT_DIR);
  if (skipExisting(out.pathname)) {
    skipped.push(id);
    return;
  }
  const speechPath = `${TMP}/speech-${id}.mp3`;
  process.stdout.write(`synth ${id} ← ${text}\n`);
  await tts(text, speechPath);
  if (withChime) concatChime(speechPath, out.pathname);
  else ffmpeg(["-i", speechPath, "-codec:a", "libmp3lame", "-q:a", "4", out.pathname]);
  made.push(id);
}

await ensureSpeechMp3("_tsugiwa", "次は、", false);
await ensureSpeechMp3("_desu", "です。", false);

const curated = new Set(ANNOUNCEMENTS_G1.map((a) => a.kanji));
const g1 = [...new Set(KYOIKU.filter((k) => k.grade === 1).map((k) => k.char))];
for (const kanji of g1) {
  if (curated.has(kanji)) continue;
  const id = genericId(kanji);
  await ensureSpeechMp3(id, `次は、「${kanji}」です。`, true);
}

console.log(
  JSON.stringify({
    voice: VOICE,
    language: LANGUAGE,
    made,
    skipped: skipped.length,
    baked: writeBaked(),
  }),
);

/**
 * Build-time 音・訓 clips. One MP3 per unique displayed reading string.
 * Voice/rate locked. Existing files skipped. Never used on the child path as live TTS.
 */
import { mkdirSync, existsSync, writeFileSync, readdirSync } from "node:fs";
import {
  collectLearningPackageReadings,
  readingSlug,
} from "../src/data/reading-audio.ts";

const OUT_DIR = new URL("../public/audio/readings/", import.meta.url);
const BAKED_FILE = new URL("../src/data/reading-audio-baked.ts", import.meta.url);
mkdirSync(OUT_DIR, { recursive: true });

const VOICE = "eve";
const LANGUAGE = "ja";
const apiKey = process.env.XAI_API_KEY;

function unslug(slug) {
  const parts = String(slug).match(/.{4}/g);
  if (!parts) return "";
  return parts.map((h) => String.fromCodePoint(Number.parseInt(h, 16))).join("");
}

function writeBaked() {
  const texts = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".mp3"))
    .map((f) => unslug(f.replace(/\.mp3$/, "")))
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b, "ja"));
  const body =
    "/** Auto-generated by scripts/synth-readings.mjs. Do not edit by hand. */\n" +
    "export const BAKED_READING_TEXTS = [\n" +
    texts.map((t) => `  ${JSON.stringify(t)},`).join("\n") +
    "\n] as const;\n";
  writeFileSync(BAKED_FILE, body);
  return texts.length;
}

async function tts(text, dest) {
  const res = await fetch("https://api.x.ai/v1/tts", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      text,
      voice_id: VOICE,
      language: LANGUAGE,
    }),
  });
  if (!res.ok) {
    const err = await res.text();
    throw new Error(`TTS ${res.status}: ${err.slice(0, 200)}`);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 400 || buf.subarray(0, 1).toString() === "{") {
    throw new Error("TTS did not return audio");
  }
  writeFileSync(dest, buf);
}

const entries = collectLearningPackageReadings();
const made = [];
const skipped = [];
const failed = [];

if (!apiKey) {
  console.error("XAI_API_KEY missing — cannot synth readings. Existing clips kept.");
} else {
  for (const e of entries) {
    const dest = new URL(`${readingSlug(e.text)}.mp3`, OUT_DIR);
    if (existsSync(dest) && dest.pathname) {
      const { statSync } = await import("node:fs");
      if (statSync(dest).size > 400) {
        skipped.push(e.text);
        continue;
      }
    }
    try {
      process.stdout.write(`synth ${e.text}\n`);
      await tts(e.text, dest);
      made.push(e.text);
    } catch (err) {
      failed.push(`${e.text}: ${err.message}`);
    }
  }
}

const baked = writeBaked();
console.log(
  JSON.stringify(
    {
      voice: VOICE,
      language: LANGUAGE,
      needed: entries.length,
      made: made.length,
      skipped: skipped.length,
      failed,
      baked,
    },
    null,
    2,
  ),
);
if (failed.length) process.exitCode = 1;
